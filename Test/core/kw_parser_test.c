static unsigned check_case(const parser_case_t* test, void* arena, size_t arena_size)
{
	/* Each module owns its arena; scratch must be released on both outcomes. */
	kinowasm_mem_set_info(kinowasm_mem_info_init(arena, arena_size));
	module_t mod = { 0 };
	kinowasm_buf_t buf;
	kinowasm_buf_set(&buf, (void*)test->image, test->size);
	kinowasm_result_t result = kinowasm_parse_module(&mod, &buf);
	if((result == RES_SUCCESS) != test->valid) {
		fprintf(stderr, "FAIL: %s result=%u expected=%s\n", test->name,
			result, test->valid ? "valid" : "invalid");
		return 1;
	}
	return 0;
}

static unsigned check_large_memidx(void* arena, size_t arena_size)
{
	/* 65537 memories: memory 0 is memory32, memory 65536 is memory64.
	 * A u16 index truncation would validate the load against memory 0. */
	static const uint8_t prefix[] = {
		0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,
		0x01, 0x04, 0x01, 0x60, 0x00, 0x00, 0x03, 0x02, 0x01, 0x00,
		0x05, 0x85, 0x80, 0x08, 0x81, 0x80, 0x04,
	};
	static const uint8_t code[] = {
		0x0a, 0x0d, 0x01, 0x0b, 0x00, 0x42, 0x00, 0x28,
		0x40, 0x80, 0x80, 0x04, 0x00, 0x1a, 0x0b,
	};
	size_t code_offset = sizeof(prefix) + 65537u * 2u;
	size_t image_size = code_offset + sizeof(code);
	uint8_t* image = calloc(image_size, 1);
	if(image == NULL)
		return 1;

	memcpy(image, prefix, sizeof(prefix));
	image[code_offset - 2] = 4; /* Last memory has i64 addresses. */
	memcpy(image + code_offset, code, sizeof(code));
	parser_case_t test = { "valid full-width memory index", image, image_size, 1 };
	unsigned failed = check_case(&test, arena, arena_size);
	image[code_offset + 5] = 0x41; /* An i32 address must be rejected. */
	test.name = "wrong address type at full-width memory index";
	test.valid = 0;
	failed += check_case(&test, arena, arena_size);
	free(image);
	return failed;
}

int main(void)
{
	size_t arena_size = 16u * 1024u * 1024u;
	void* arena = malloc(arena_size);
	if(arena == NULL)
		return 1;

	unsigned failed = 0;
	for(size_t i = 0; i < sizeof(cases) / sizeof(cases[0]); i++)
		failed += check_case(&cases[i], arena, arena_size);

	failed += check_large_memidx(arena, arena_size);
	kinowasm_mem_set_info(NULL);
	free(arena);
	printf("parser cases=%zu failed=%u\n", sizeof(cases) / sizeof(cases[0]) + 2, failed);
	return failed != 0;
}
